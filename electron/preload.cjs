const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('desktop', {
  pickFiles: () => ipcRenderer.invoke('files:pick'),
  fetchArticle: url => ipcRenderer.invoke('article:fetch', url),
  fetchSource: request => ipcRenderer.invoke('sources:fetch', request),
  openSource: (source, request, mode) => ipcRenderer.invoke('sources:open', source, request, mode),
  onSourceSnapshot: callback => { const listener = (_event, snapshot) => callback(snapshot); ipcRenderer.on('sources:snapshot', listener); return () => ipcRenderer.removeListener('sources:snapshot', listener); },
  onSourceRetry: callback => { const listener = (_event, value) => callback(value.sourceId); ipcRenderer.on('sources:retry', listener); return () => ipcRenderer.removeListener('sources:retry', listener); },
  minimize: () => ipcRenderer.send('window:control', 'minimize'),
  maximize: () => ipcRenderer.send('window:control', 'maximize'),
  close: () => ipcRenderer.send('window:control', 'close'),
  fullscreen: () => ipcRenderer.invoke('window:fullscreen'),
  openExternal: url => ipcRenderer.invoke('link:open', url),
  downloads: {
    stopCloud: id=>ipcRenderer.invoke('downloads:stop-cloud',id),
    onPrepared: callback=>{const listener=(_e,value)=>callback(value);ipcRenderer.on('downloads:prepared',listener);return ()=>ipcRenderer.removeListener('downloads:prepared',listener);},
    onResolveStatus: callback=>{const listener=(_e,value)=>callback(value);ipcRenderer.on('downloads:resolve-status',listener);return ()=>ipcRenderer.removeListener('downloads:resolve-status',listener);},
    setCloudContext: (id,active)=>ipcRenderer.invoke('downloads:cloud-context',{id,active}),
    resolveTorrent: request=>ipcRenderer.invoke('downloads:resolve-torrent',request),
    cancelResolution: id=>ipcRenderer.invoke('downloads:cancel-resolution',id),
    openCloud: context=>ipcRenderer.invoke('downloads:open-cloud',context),
    onPage: callback=>{const listener=(_event,page)=>callback(page);ipcRenderer.on('downloads:page',listener);return ()=>ipcRenderer.removeListener('downloads:page',listener);},
    list: () => ipcRenderer.invoke('downloads:list'),
    start: request => ipcRenderer.invoke('downloads:start',request),
    cancel: id => ipcRenderer.invoke('downloads:cancel',id),
    retry: id => ipcRenderer.invoke('downloads:retry',id),
    read: id => ipcRenderer.invoke('downloads:read',id),
    save: id => ipcRenderer.invoke('downloads:save',id),
    extract: request=>ipcRenderer.invoke('downloads:extract',request),
    acknowledge: id=>ipcRenderer.invoke('downloads:acknowledge',id),
    remove: id => ipcRenderer.invoke('downloads:remove',id),
    onChange: callback => { const listener=(_event,jobs)=>callback(jobs);ipcRenderer.on('downloads:changed',listener);return ()=>ipcRenderer.removeListener('downloads:changed',listener); },
  },
  platform: process.platform,
});
